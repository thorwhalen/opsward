"""Reuse a skill as a subagent: declare it in the skill, generate the twin, check the sync.

A Claude Code subagent is a Markdown file under ``.claude/agents/`` whose frontmatter
can *preload* a skill (``skills: [name]`` injects the full ``SKILL.md`` body). So a skill
that is also useful in its own context needs nothing but a thin twin that preloads it,
restricts tools, picks a model and states the reply contract. The single source of
truth stays in the skill: it opts in with spec-legal ``metadata`` keys (the Agent Skills
spec allows string pairs there, and other hosts ignore them). Quote the values so a
strict validator sees strings::

    ---
    name: fleet-sweep
    description: ...
    metadata:
      subagent: "true"
      subagent-tools: "Bash, Read, Grep"
      subagent-model: "sonnet"
      subagent-reply-lines: "5"
      subagent-name: "fleet-sweeper"
    ---

Only ``subagent`` is required; the defaults are ``Read, Grep, Glob, Bash``, no model
(the host picks), 5 lines, and the skill's own name. Three pure functions do the
work, so ``generate`` and ``maintain`` share one source: :func:`subagent_spec` reads
the declaration, :func:`render_subagent` renders the twin (with a marker line
carrying a hash of what it was rendered from), and :func:`twin_status` classifies
every skill/agent pair in a scan. Decision record:
``misc/docs/decisions/0009-skills-declare-their-subagent-twin.md``.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Iterator, Optional

from opsward.base import (
    AgentInfo,
    GeneratedFile,
    MaintenanceSuggestion,
    ScanResult,
    SkillInfo,
)
from opsward.util import read_text_safe

_META_FLAG = "subagent"
_META_PREFIX = "subagent-"
_TRUE_VALUES = frozenset({"true", "yes", "1", "on"})
_DEFAULT_TOOLS = "Read, Grep, Glob, Bash"
_DEFAULT_REPLY_LINES = 5
_RENDER_VERSION = 1  # bump when the rendered body changes, so old twins read as stale
_NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
_MARKER_RE = re.compile(
    r"<!-- generated by opsward from (?P<source>\S+); source-hash: (?P<hash>[0-9a-f]+) -->"
)
_MARKER = "<!-- generated by opsward from {source}; source-hash: {hash} -->"
_SUGGESTION_CATEGORY = "subagent_twin"


@dataclass(frozen=True)
class SubagentSpec:
    """What a skill declared about its subagent twin, with defaults applied."""

    skill_name: str
    name: str
    description: str
    tools: str
    model: Optional[str]
    reply_lines: int

    def source_hash(self) -> str:
        """Hash of everything the rendered twin depends on, so drift is detectable."""
        payload = json.dumps(
            {**self.__dict__, "render": _RENDER_VERSION}, sort_keys=True
        )
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:12]

    def problems(self) -> list[str]:
        """Why this declaration cannot be rendered (empty = fine).

        >>> SubagentSpec('s', '../x', '', 'Bash: all', None, 0).problems()
        ['no frontmatter description (the twin reuses it as its trigger)', 'subagent-name `../x` is not a valid agent name', 'subagent-reply-lines must be at least 1', 'subagent-tools must not contain `: `']
        """
        out = []
        if not self.description:
            out.append("no frontmatter description (the twin reuses it as its trigger)")
        if not _NAME_RE.match(self.name):
            out.append(f"subagent-name `{self.name}` is not a valid agent name")
        if self.reply_lines < 1:
            out.append("subagent-reply-lines must be at least 1")
        if ": " in self.tools:
            out.append("subagent-tools must not contain `: `")
        return out


def _is_true(value: object) -> bool:
    return str(value).strip().lower() in _TRUE_VALUES


def _text(value: object) -> str:
    """A frontmatter value as one line of text; a mis-parsed map becomes its values."""
    if isinstance(value, dict):
        value = " ".join(f"{k}: {v}" for k, v in value.items())
    return " ".join(str(value or "").split())


def subagent_spec(skill: SkillInfo) -> Optional[SubagentSpec]:
    """Return the twin a skill declares under ``metadata``, or ``None``.

    >>> from pathlib import Path
    >>> from opsward.base import SkillInfo
    >>> s = SkillInfo(name='sweep', path=Path('/x/sweep'), has_skill_md=True,
    ...     description='Sweep the fleet and report.',
    ...     frontmatter={'name': 'sweep', 'metadata': {'subagent': 'true', 'subagent-model': 'haiku'}})
    >>> spec = subagent_spec(s)
    >>> (spec.name, spec.tools, spec.model, spec.reply_lines)
    ('sweep', 'Read, Grep, Glob, Bash', 'haiku', 5)
    >>> subagent_spec(SkillInfo(name='plain', path=Path('/x/plain'))) is None
    True
    """
    meta = skill.frontmatter.get("metadata")
    if not isinstance(meta, dict) or not _is_true(meta.get(_META_FLAG, "")):
        return None

    def get(key: str, default: object = None) -> object:
        return meta.get(_META_PREFIX + key, default)

    try:
        reply_lines = int(_text(get("reply-lines", _DEFAULT_REPLY_LINES)))
    except ValueError:
        reply_lines = _DEFAULT_REPLY_LINES
    description = _text(
        skill.frontmatter.get("description")
    )  # the body is not a trigger
    model = _text(get("model")) or None
    return SubagentSpec(
        skill_name=skill.name,
        name=_text(get("name")) or skill.name,
        description=description,
        tools=_text(get("tools")) or _DEFAULT_TOOLS,
        model=model,
        reply_lines=reply_lines,
    )


def render_subagent(spec: SubagentSpec, *, source: str) -> str:
    """Render the twin agent file for *spec*; *source* is the skill's repo-relative path.

    The body is deliberately short: the skill's full content is preloaded by the host
    through the ``skills`` field, so the twin only adds the context contract.

    >>> spec = SubagentSpec('sweep', 'sweep', 'Sweep and report.', 'Bash', 'haiku', 3)
    >>> text = render_subagent(spec, source='.claude/skills/sweep/SKILL.md')
    >>> text.splitlines()[1:4]
    ['name: sweep', 'description: Sweep and report.', 'tools: Bash']
    >>> 'skills: [sweep]' in text and 'at most 3 lines' in text
    True
    """
    lines = [
        "---",
        f"name: {spec.name}",
        f"description: {_yaml_scalar(spec.description)}",
        f"tools: {_yaml_scalar(spec.tools)}",
    ]
    if spec.model:
        lines.append(f"model: {spec.model}")
    lines.append(f"skills: [{spec.skill_name}]")
    lines.append("---")
    body = f"""
{_MARKER.format(source=source, hash=spec.source_hash())}

You are the `{spec.skill_name}` skill running in your own context. Its full instructions are preloaded above; follow them for the task in your brief, and spend your context freely on reading, scanning and running commands so the caller does not have to.

Reply in at most {spec.reply_lines} lines: the answer or the finding first, then what the caller must do, if anything. Anything longer goes in a file (a report under the project's docs folder or the working folder named in your brief) and your reply names its path. Never return raw command output.
"""
    return "\n".join(lines) + "\n" + body.lstrip("\n")


def _yaml_scalar(text: str) -> str:
    """Quote a one-line YAML scalar when it needs it (JSON strings are valid YAML).

    >>> _yaml_scalar('plain words'), _yaml_scalar('has: colon'), _yaml_scalar('')
    ('plain words', '"has: colon"', '""')
    """
    text = " ".join(text.split())
    if not text:
        return '""'
    if any(c in text for c in ":#{}[],&*!|>'\"%@`") or text[0] in "-?":
        return json.dumps(text, ensure_ascii=False)
    return text


def _source_rel(skill_md: Path, root: Path) -> str:
    try:
        return skill_md.relative_to(root).as_posix()
    except ValueError:
        return skill_md.as_posix()


@dataclass(frozen=True)
class TwinStatus:
    """One skill/agent pair as :func:`twin_status` sees it."""

    skill: str
    agent: str
    state: (
        str  # 'in_sync' | 'stale' | 'missing' | 'handwritten' | 'invalid' | 'duplicate'
    )
    declared: bool = False  # the skill declares a twin
    content: str = ""  # the rendered twin, for a diff or a write
    detail: str = ""  # problems, or the other skill a duplicate collides with
    path: str = ""  # the agent file, repo-relative, when one exists


def _read_marker(agent: AgentInfo) -> Optional[tuple[str, str]]:
    m = _MARKER_RE.search(read_text_safe(agent.path))
    return (m.group("source"), m.group("hash")) if m else None


def _preloaded_skills(agent: AgentInfo) -> set[str]:
    """Names in the agent frontmatter's ``skills:`` field (inline list or block list)."""
    text = read_text_safe(agent.path)
    if not text.startswith("---"):
        return set()
    fence = text.find("\n---", 3)
    frontmatter = text[:fence] if fence > 0 else text
    m = re.search(r"^skills:[ \t]*(.*)$((?:\n[ \t]+-[^\n]*)*)", frontmatter, re.M)
    if not m:
        return set()
    inline, block = m.group(1), m.group(2)
    names = re.findall(r"[A-Za-z0-9_.:-]+", inline.strip("[] "))
    names += re.findall(r"^[ \t]+-[ \t]*([A-Za-z0-9_.:-]+)", block, re.M)
    return {n.strip("'\"") for n in names}


def _declared(sr: ScanResult) -> Iterator[tuple[SkillInfo, SubagentSpec]]:
    for skill in sr.skills:
        spec = subagent_spec(skill)
        if spec is not None:
            yield skill, spec


def twin_status(sr: ScanResult) -> Iterator[TwinStatus]:
    """Classify every declared twin and every hand-written agent that preloads a skill.

    - ``invalid``: the declaration cannot be rendered (see ``SubagentSpec.problems``).
    - ``duplicate``: two skills declare the same twin name; the first wins, the rest are reported.
    - ``missing``: the skill declares a twin and no agent file exists.
    - ``stale``: the agent file was generated from a declaration that has since changed.
    - ``in_sync``: generated and current.
    - ``handwritten``: an agent opsward did not generate, either carrying the name a skill
      declares for its twin (``declared=True``), or sharing a non-declaring skill's name or
      preloading it via ``skills:`` (``declared=False``).
    """
    agents = {a.name: a for a in sr.agents}
    by_stem = {a.path.stem: a for a in sr.agents}
    rel = lambda a: _source_rel(a.path, sr.project_root)  # noqa: E731
    taken: dict[str, str] = {}
    declared_skills: set[str] = set()
    for skill, spec in _declared(sr):
        declared_skills.add(skill.name)
        problems = spec.problems()
        if problems:
            yield TwinStatus(
                skill.name, spec.name, "invalid", True, detail="; ".join(problems)
            )
            continue
        if spec.name in taken:
            yield TwinStatus(
                skill.name, spec.name, "duplicate", True, detail=taken[spec.name]
            )
            continue
        taken[spec.name] = skill.name
        content = render_subagent(
            spec, source=_source_rel(skill.path / "SKILL.md", sr.project_root)
        )
        agent = agents.get(spec.name) or by_stem.get(
            spec.name
        )  # a file in the way counts too
        if agent is None:
            yield TwinStatus(skill.name, spec.name, "missing", True, content)
            continue
        marker = _read_marker(agent)
        if marker is None:
            yield TwinStatus(
                skill.name, spec.name, "handwritten", True, content, path=rel(agent)
            )
        elif marker[1] != spec.source_hash():
            yield TwinStatus(
                skill.name, spec.name, "stale", True, content, path=rel(agent)
            )
        else:
            yield TwinStatus(
                skill.name, spec.name, "in_sync", True, content, path=rel(agent)
            )
    for skill in sr.skills:
        if skill.name in declared_skills:
            continue
        twin = agents.get(skill.name)
        if twin is None:
            twin = next(
                (a for a in sr.agents if skill.name in _preloaded_skills(a)), None
            )
        if twin is not None and _read_marker(twin) is None:
            yield TwinStatus(
                skill.name, twin.name, "handwritten", False, path=rel(twin)
            )


def subagent_files(sr: ScanResult) -> Iterator[GeneratedFile]:
    """Yield the twin agent file for every validly declared skill (missing or not).

    Callers that must not overwrite (the CLI) skip existing targets; the marker in a
    generated file is what :func:`twin_status` uses to tell a stale twin from a
    hand-written one. Invalid and duplicate declarations yield nothing; ``maintain``
    reports them.
    """
    agents_dir = sr.project_root / ".claude" / "agents"
    for t in twin_status(sr):
        if t.declared and t.state in ("missing", "stale", "in_sync"):
            yield GeneratedFile(
                target_path=agents_dir / f"{t.agent}.md", content=t.content
            )


def twin_for_rendered_skill(
    skill_md_text: str, skill_md_path: Path, root: Path
) -> Optional[GeneratedFile]:
    """The twin of a skill that is about to be written (so one ``generate`` run creates both).

    >>> from pathlib import Path
    >>> text = '---\\nname: s\\ndescription: Do the thing.\\nmetadata:\\n  subagent: "true"\\n---\\nbody\\n'
    >>> gf = twin_for_rendered_skill(text, Path('/p/.claude/skills/s/SKILL.md'), Path('/p'))
    >>> gf.target_path.as_posix(), 'skills: [s]' in gf.content
    ('/p/.claude/agents/s.md', True)
    """
    from opsward.scan import _description_of, _parse_frontmatter  # read-only helpers

    fm = _parse_frontmatter(skill_md_text)
    skill = SkillInfo(
        name=skill_md_path.parent.name,
        path=skill_md_path.parent,
        has_skill_md=True,
        description=_description_of(skill_md_text, fm),
        frontmatter=fm,
    )
    spec = subagent_spec(skill)
    if spec is None or spec.problems():
        return None
    return GeneratedFile(
        target_path=root / ".claude" / "agents" / f"{spec.name}.md",
        content=render_subagent(spec, source=_source_rel(skill_md_path, root)),
    )


def check_subagent_twins(sr: ScanResult) -> Iterable[MaintenanceSuggestion]:
    """``maintain`` check: every twin that is not generated and current."""
    for t in twin_status(sr):
        agent_path = t.path or f".claude/agents/{t.agent}.md"
        if t.state == "invalid":
            text = f"Skill `{t.skill}` declares a subagent twin that cannot be rendered: {t.detail}"
        elif t.state == "duplicate":
            text = (
                f"Skill `{t.skill}` declares subagent twin `{t.agent}`, already declared by "
                f"skill `{t.detail}` — give one of them a distinct `subagent-name`"
            )
        elif t.state == "missing":
            text = f"Skill `{t.skill}` declares a subagent twin but `{agent_path}` does not exist — run `opsward generate --write`"
        elif t.state == "stale":
            text = (
                f"Generated agent `{agent_path}` is out of date with skill `{t.skill}`'s declaration — "
                "delete it and run `opsward generate --write`"
            )
        elif t.state == "handwritten" and t.declared:
            text = (
                f"Agent `{agent_path}` exists but was not generated by opsward, while skill `{t.skill}` "
                "declares it — move anything it adds into the skill, delete it, and run `opsward generate --write`"
            )
        elif t.state == "handwritten":
            text = (
                f"Agent `{agent_path}` is a hand-written twin of skill `{t.skill}` — declare "
                '`metadata: subagent: "true"` in the skill and let opsward generate it, so the two cannot drift'
            )
        else:
            continue
        yield MaintenanceSuggestion(
            category=_SUGGESTION_CATEGORY, description=text, diff=t.content
        )


def twin_summary(sr: ScanResult) -> dict[str, int]:
    """Counts by state, for the diagnosis note.

    >>> from pathlib import Path
    >>> twin_summary(ScanResult(project_root=Path('/tmp/empty')))
    {}
    """
    counts: dict[str, int] = {}
    for t in twin_status(sr):
        counts[t.state] = counts.get(t.state, 0) + 1
    return counts
